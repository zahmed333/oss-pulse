"""Markdown (terminal, PR comment, job summary) and JSON renderings of a CheckResult."""

from __future__ import annotations

import json

from oss_pulse.check.result import LEVELS, CheckResult
from oss_pulse.safe_text import md_code, md_text

REPORT_MARKER = "<!-- oss-pulse-report -->"
NONE = "–"


def render_markdown(result: CheckResult) -> str:
    lines = [REPORT_MARKER, "## Supply-chain risk report", "", _summary_line(result), ""]
    lines += _unavailable_signal_warnings(result)
    lines += _dependency_table(result)
    lines += _findings_table(result)
    lines += ["", _footer(result)]
    return "\n".join(lines) + "\n"


def render_json(result: CheckResult) -> str:
    return json.dumps(
        {
            "source": result.source,
            "window_days": result.window_days,
            "summary": result.counts(),
            "degraded": result.unavailable_signals,
            "dependencies": result.rows,
            "findings": result.findings,
        },
        indent=2,
        default=str,
    )


def _summary_line(result: CheckResult) -> str:
    counts = result.counts()
    by_level = ", ".join(f"{counts[level]} {level}" for level in LEVELS if counts[level])
    source = md_code(result.source, in_table=False)
    return f"**{len(result.rows)} dependencies** in {source} · {by_level}"


def _unavailable_signal_warnings(result: CheckResult) -> list[str]:
    warnings = [f"> [!WARNING]\n> Not checked: {md_text(s)}" for s in result.unavailable_signals]
    return [*warnings, ""] if warnings else []


def _dependency_table(result: CheckResult) -> list[str]:
    lines = [
        "| | Package | Version | Repository | Why | Last release | Last commit | Bus factor |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in result.rows:
        version = md_text(row["resolved_version"] or NONE)
        attested = " (attested)" if row.get("has_provenance") else ""
        reasons = "<br>".join(md_text(r) for r in row["risk_reasons"]) or NONE
        bus_factor = NONE if row["bus_factor"] is None else str(row["bus_factor"])
        lines.append(
            f"| {row['risk_level']} | {md_code(row['pypi_package'])} | {version}{attested} "
            f"| {_repo_link(row['repo_name'])} | {reasons} "
            f"| {_age(row['days_since_last_release'])} | {_age(row['days_since_last_commit'])} "
            f"| {bus_factor} |"
        )
    return lines


def _findings_table(result: CheckResult) -> list[str]:
    if not result.findings:
        return []
    lines = [
        "",
        f"<details><summary><b>Findings</b> ({len(result.findings)})</summary>",
        "",
        "| Severity | Package | Rule | Finding | Where | Evidence |",
        "|---|---|---|---|---|---|",
    ]
    for f in result.findings:
        lines.append(
            f"| {f['severity']} | {md_code(f['target'])} | {f['rule_id']} "
            f"| {md_text(f['title'])}: {md_text(f['detail'])} "
            f"| {md_code(f['location'] or NONE)} | {md_code(f['evidence'] or NONE, 100)} |"
        )
    return [*lines, "</details>"]


def _footer(result: CheckResult) -> str:
    return (
        "<sub>Attested means the release has a Trusted Publishing attestation (PEP 740). "
        f"Activity window: last {result.window_days} days. Bus factor = fewest people "
        "responsible for ≥50% of commits and opened PRs. Generated by oss-pulse; "
        "run `oss-pulse rules` for the full rule catalogue.</sub>"
    )


def _repo_link(repo_name: str | None) -> str:
    return f"[{repo_name}](https://github.com/{repo_name})" if repo_name else NONE


def _age(days: int | None) -> str:
    if days is None:
        return NONE
    return "today" if days == 0 else f"{days}d ago"
